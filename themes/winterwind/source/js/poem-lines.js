  function pick() {
    if (POEMS.length === 0) return null;
    if (POEMS.length === 1) return POEMS[0];
    var last = readLast();
    var i = Math.floor(Math.random() * POEMS.length);
    var guard = 0;
    while (i === last && guard < 12) {
      i = Math.floor(Math.random() * POEMS.length);
      guard++;
    }
    saveLast(i);
    return POEMS[i];
  }

  function show(box, poem) {
    if (!poem) return;
    box.querySelector(".poem-text").textContent = poem.t;
    box.querySelector(".poem-from").textContent = "—— " + poem.a + "《" + poem.s + "》";
    box.title = poem.a + "《" + poem.s + "》  ·  点击换一句";
  }

  function init() {
    var box = document.getElementById("poem-line");
    if (!box) return;

    show(box, pick());
    box.classList.add("on");

    var next = function () {
      show(box, pick());
    };
    box.addEventListener("click", next);
    box.addEventListener("keydown", function (e) {
      if (e.key === "Enter" || e.key === " " || e.key === "Spacebar") {
        e.preventDefault();
        next();
      }
    });
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
